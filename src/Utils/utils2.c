#include "../../includes/minishell.h"

int	is_special_op(char c)
{
	return (is_expandable(c) || c == '.'
		|| c == '+' || c == '=' || c == '}' || c == '{'
		|| c == '*' || c == '#' || c == '@' || c == '^');
}
